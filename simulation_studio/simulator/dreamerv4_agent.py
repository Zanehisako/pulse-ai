def _resolve_native_model_config(
    *,
    obs_dim: int,
    action_dim: int,
    preset: str = "default",
    hidden_size: int | None = None,
    stoch_categories: int | None = None,
    stoch_classes: int | None = None,
    mlp_units: int | None = None,
) -> Dict[str, int]:
    if preset not in NATIVE_MODEL_PRESETS:
        raise ValueError(
            f"Unknown native model preset {preset!r}. "
            f"Expected one of {sorted(NATIVE_MODEL_PRESETS)}."
        )

    config = dict(NATIVE_MODEL_PRESETS[preset])
    overrides = {
        "hidden_size": hidden_size,
        "stoch_categories": stoch_categories,
        "stoch_classes": stoch_classes,
        "mlp_units": mlp_units,
    }
    for key, value in overrides.items():
        if value is not None:
            if int(value) < 1:
                raise ValueError(f"{key} must be >= 1, got {value!r}.")
            config[key] = int(value)

    return {
        "obs_dim": int(obs_dim),
        "action_dim": int(action_dim),
        **config,
    }


