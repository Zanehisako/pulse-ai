class RSSM(nn.Module):
    """Recurrent State-Space Model with categorical stochastic latents."""

    def __init__(
        self,
        obs_dim: int = OBS_DIM,
        action_dim: int = DREAMER_ACTION_DIM,
        hidden_size: int = 256,
        stoch_categories: int = 16,
        stoch_classes: int = 16,
        mlp_units: int = 256,
    ):
        super().__init__()
        self.obs_dim = obs_dim
        self.action_dim = action_dim
        self.hidden_size = hidden_size
        self.stoch_categories = stoch_categories
        self.stoch_classes = stoch_classes
        self.stoch_dim = stoch_categories * stoch_classes  # 256
        self.state_feat_dim = hidden_size + self.stoch_dim  # 512
        self.mlp_units = mlp_units

        # --- Encoder ---
        self.encoder = nn.Sequential(
            nn.Linear(obs_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, mlp_units),
        )

        # --- Sequence model (GRU) ---
        self.gru_input = nn.Linear(self.stoch_dim + action_dim, hidden_size)
        self.gru_cell = nn.GRUCell(hidden_size, hidden_size)

        # --- Posterior  q(z | h, embed) ---
        self.posterior_net = nn.Sequential(
            nn.Linear(hidden_size + mlp_units, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, self.stoch_dim),
        )

        # --- Prior  p(z | h) ---
        self.prior_net = nn.Sequential(
            nn.Linear(hidden_size, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, self.stoch_dim),
        )

        # --- Observation decoder ---
        self.obs_decoder = nn.Sequential(
            nn.Linear(self.state_feat_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, obs_dim),
        )

        # --- Reward predictor ---
        self.reward_head = nn.Sequential(
            nn.Linear(self.state_feat_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, 128),
            nn.LayerNorm(128),
            nn.SiLU(),
            nn.Linear(128, 1),
        )

        # --- Continue predictor ---
        self.continue_head = nn.Sequential(
            nn.Linear(self.state_feat_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, 128),
            nn.LayerNorm(128),
            nn.SiLU(),
            nn.Linear(128, 1),
        )

    # ----- helpers -----

    def initial_state(
        self, batch_size: int, device: torch.device | None = None
    ) -> Dict[str, torch.Tensor]:
        """Return a zero-initialised recurrent state dict."""
        dev = device or next(self.parameters()).device
        return {
            "h": torch.zeros(batch_size, self.hidden_size, device=dev),
            "z": torch.zeros(batch_size, self.stoch_dim, device=dev),
        }

    def state_features(self, state: Dict[str, torch.Tensor]) -> torch.Tensor:
        """Concatenate deterministic and stochastic state → (B, 512)."""
        return torch.cat([state["h"], state["z"]], dim=-1)

    def _reshape_stoch_logits(self, raw: torch.Tensor) -> torch.Tensor:
        """(B, stoch_dim) → (B, n_categories, n_classes)."""
        return raw.view(-1, self.stoch_categories, self.stoch_classes)

    def _sample_stoch(self, logits: torch.Tensor) -> torch.Tensor:
        """Sample stoch state from (B, n_cat, n_cls) logits → (B, stoch_dim)."""
        z = _straight_through_one_hot(logits, self.stoch_classes)
        return z.view(-1, self.stoch_dim)

    # ----- sequence step -----

    def sequence_step(
        self,
        prev_state: Dict[str, torch.Tensor],
        prev_action: torch.Tensor,
    ) -> torch.Tensor:
        """Advance deterministic state h given previous z and action."""
        x = torch.cat([prev_state["z"], prev_action], dim=-1)
        x = self.gru_input(x)
        x = F.silu(x)
        h = self.gru_cell(x, prev_state["h"])
        return h

    def posterior(
        self, h: torch.Tensor, embed: torch.Tensor
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """Posterior logits and sampled z given h and observation embedding."""
        x = torch.cat([h, embed], dim=-1)
        logits = self._reshape_stoch_logits(self.posterior_net(x))
        z = self._sample_stoch(logits)
        return logits, z

    def prior(self, h: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """Prior logits and sampled z from h alone."""
        logits = self._reshape_stoch_logits(self.prior_net(h))
        z = self._sample_stoch(logits)
        return logits, z

    def encode(self, obs: torch.Tensor) -> torch.Tensor:
        """Encode observation vector → embedding."""
        return self.encoder(obs)

    def decode_obs(self, feat: torch.Tensor) -> torch.Tensor:
        """Predict symlog(obs) from state features."""
        return self.obs_decoder(feat)

    def decode_reward(self, feat: torch.Tensor) -> torch.Tensor:
        """Predict symlog(reward) from state features."""
        return self.reward_head(feat)

    def decode_continue(self, feat: torch.Tensor) -> torch.Tensor:
        """Predict continue logit from state features."""
        return self.continue_head(feat)

    # ----- full forward (observe sequence) -----

    def observe(
        self,
        obs_seq: torch.Tensor,
        action_seq: torch.Tensor,
        is_first_seq: torch.Tensor,
        prev_state: Dict[str, torch.Tensor] | None = None,
    ) -> Dict[str, Any]:
        """Process a sequence of observations and actions.

        Parameters
        ----------
        obs_seq      : (B, T, obs_dim)
        action_seq   : (B, T, action_dim)
        is_first_seq : (B, T)
        prev_state   : optional initial state dict

        Returns
        -------
        Dict with keys: h_seq, post_logits, prior_logits, post_z_seq,
                        feat_seq, final_state  — all (B, T, ...).

        MPS optimisation
        ----------------
        The inner loop is the primary training bottleneck on Apple Metal
        because each GRU timestep launches many small MPS kernels.  This
        version minimises per-step overhead by:

        * Pre-allocating output tensors and writing via sliced assignment
          instead of appending to Python lists and ``torch.stack``-ing
          (avoids T intermediate allocations + 1 stack copy).
        * Fusing the first-step mask multiply into a single in-place op
          instead of two separate multiplies on h and z.
        * Computing the encoder embedding once for the whole sequence
          before entering the loop (already done, kept for clarity).
        """
        B, T, _ = obs_seq.shape
        device = obs_seq.device

        if prev_state is None:
            prev_state = self.initial_state(B, device)

        # Encode all observations in one batched forward pass.
        embed_seq = self.encode(obs_seq.reshape(B * T, -1)).view(B, T, -1)

        # Pre-allocate output tensors to avoid per-step list appends and
        # the final torch.stack copy — a significant MPS allocation saving.
        h_seq = torch.empty(B, T, self.hidden_size, device=device)
        post_logits_seq = torch.empty(
            B, T, self.stoch_categories, self.stoch_classes, device=device
        )
        prior_logits_seq = torch.empty(
            B, T, self.stoch_categories, self.stoch_classes, device=device
        )
        post_z_seq = torch.empty(B, T, self.stoch_dim, device=device)

        h = prev_state["h"]
        z = prev_state["z"]

        for t in range(T):
            # Reset recurrent state for episodes that just started.
            # Fused mask: one multiply on the concatenated [h, z] is
            # cheaper than two separate masked multiplies on MPS.
            mask = is_first_seq[:, t].unsqueeze(-1)  # (B, 1)
            if mask.any():
                inv = 1.0 - mask
                h = h * inv
                z = z * inv

            # Deterministic step — inlined to avoid dict allocation
            x = torch.cat([z, action_seq[:, t]], dim=-1)
            x = F.silu(self.gru_input(x))
            h = self.gru_cell(x, h)

            # Posterior
            post_inp = torch.cat([h, embed_seq[:, t]], dim=-1)
            post_raw = self.posterior_net(post_inp)
            post_logits = post_raw.view(B, self.stoch_categories, self.stoch_classes)
            z = self._sample_stoch(post_logits)

            # Prior (for KL — detached from the posterior path)
            prior_raw = self.prior_net(h)
            prior_logits = prior_raw.view(B, self.stoch_categories, self.stoch_classes)

            # Write into pre-allocated tensors
            h_seq[:, t] = h
            post_logits_seq[:, t] = post_logits
            prior_logits_seq[:, t] = prior_logits
            post_z_seq[:, t] = z

        feat_seq = torch.cat([h_seq, post_z_seq], dim=-1)  # (B, T, state_feat_dim)

        return {
            "h_seq": h_seq,
            "post_logits": post_logits_seq,
            "prior_logits": prior_logits_seq,
            "post_z_seq": post_z_seq,
            "feat_seq": feat_seq,
            "final_state": {"h": h, "z": z},
        }


