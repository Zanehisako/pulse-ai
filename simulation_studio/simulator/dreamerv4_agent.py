class DreamerV4PolicyAgent:
    """Drop-in replacement for the JAX DreamerV3 policy agent.

    Provides the same ``init_policy`` / ``policy`` interface expected by
    ``engine.trained_official_dreamerv3_controller``.
    """

    def __init__(
        self,
        rssm: RSSM,
        actor: Actor,
        *,
        device: torch.device | None = None,
    ):
        self.rssm = rssm
        self.actor = actor
        self.device = device or torch.device("cpu")
        self.rssm.to(self.device).eval()
        self.actor.to(self.device).eval()

    # ---- interface ----

    def init_policy(self, batch_size: int) -> Dict[str, np.ndarray]:
        """Return initial recurrent carry as numpy arrays."""
        state = self.rssm.initial_state(batch_size, self.device)
        return {k: v.detach().cpu().numpy() for k, v in state.items()}

    @torch.no_grad()
    def policy(
        self,
        carry: Dict[str, np.ndarray],
        obs: Dict[str, np.ndarray],
        mode: str = "eval",
    ) -> Tuple[Dict[str, np.ndarray], Dict[str, np.ndarray], Dict]:
        """Select action given observation and carry.

        Parameters
        ----------
        carry : dict of numpy arrays ("h", "z")
        obs   : dict  {"vector", "reward", "is_first", "is_last", "is_terminal"}
        mode  : "eval" or "explore"

        Returns
        -------
        (new_carry, acts, info)
        """
        # Reconstruct torch state
        h = torch.as_tensor(carry["h"], dtype=torch.float32, device=self.device)
        z = torch.as_tensor(carry["z"], dtype=torch.float32, device=self.device)

        vector = np.asarray(obs["vector"], dtype=np.float32)
        is_first = np.asarray(obs["is_first"]).reshape(-1).astype(bool)

        B = h.shape[0]

        # Reset state for batch elements where is_first is True
        for b in range(B):
            if is_first[b]:
                h[b] = 0.0
                z[b] = 0.0

        obs_t = torch.as_tensor(vector, dtype=torch.float32, device=self.device)
        if obs_t.ndim == 1:
            obs_t = obs_t.unsqueeze(0)

        prev_action = torch.zeros(B, self.actor.action_dim, device=self.device)

        state = {"h": h, "z": z}

        # Deterministic step
        new_h = self.rssm.sequence_step(state, prev_action)

        # Encode observation and get posterior
        embed = self.rssm.encode(obs_t)
        _, new_z = self.rssm.posterior(new_h, embed)

        new_state = {"h": new_h, "z": new_z}
        feat = self.rssm.state_features(new_state)

        # Select action
        if mode == "eval":
            action = self.actor.act_eval(feat)
        else:
            action, _, _ = self.actor(feat, sample=True)

        # Clip to [-1, 1]
        action_np = (
            action.detach()
            .cpu()
            .numpy()
            .clip(CONTINUOUS_ACTION_LOW, CONTINUOUS_ACTION_HIGH)
        )

        new_carry = {k: v.detach().cpu().numpy() for k, v in new_state.items()}
        acts = {"action": action_np}
        return new_carry, acts, {}


