def _write_latest_marker(checkpoint_file: Path) -> None:
    """Point the sibling ``latest`` marker at *checkpoint_file*."""
    latest_path = checkpoint_file.parent / "latest"
    try:
        if latest_path.is_symlink() or latest_path.exists():
            latest_path.unlink()
        latest_path.symlink_to(checkpoint_file.name)
    except OSError:
        latest_path.write_text(checkpoint_file.name, encoding="utf-8")


def _resolve_checkpoint_from_latest(ckpt_dir: Path) -> Path | None:
    latest_path = ckpt_dir / "latest"
    if not latest_path.exists():
        return None
    try:
        if latest_path.is_symlink():
            target = Path(os.readlink(str(latest_path)))
        else:
            target = Path(latest_path.read_text(encoding="utf-8").strip())
    except OSError:
        return None
    if not str(target):
        return None
    resolved = (ckpt_dir / target).resolve()
    if not resolved.exists():
        return None
    try:
        return Path(resolve_dreamerv4_checkpoint_artifact(resolved))
    except FileNotFoundError:
        return resolved if resolved.is_file() else None


def _find_checkpoint_file_in_directory(directory: Path) -> Path | None:
    for filename in DREAMERV4_CHECKPOINT_CANDIDATE_NAMES:
        direct = directory / filename
        if direct.is_file():
            return direct

    via_latest = _resolve_checkpoint_from_latest(directory)
    if via_latest is not None:
        return via_latest

    pt_files = sorted(
        [candidate for candidate in directory.iterdir() if candidate.is_file() and candidate.suffix == ".pt"],
        key=lambda candidate: candidate.stat().st_mtime,
        reverse=True,
    )
    if pt_files:
        return pt_files[0]

    nested_ckpt_dir = directory / "ckpt"
    if nested_ckpt_dir.is_dir():
        nested = _find_checkpoint_file_in_directory(nested_ckpt_dir)
        if nested is not None:
            return nested

    child_dirs = sorted(
        [candidate for candidate in directory.iterdir() if candidate.is_dir()],
        key=lambda candidate: candidate.stat().st_mtime,
        reverse=True,
    )
    for child_dir in child_dirs:
        for filename in DREAMERV4_CHECKPOINT_CANDIDATE_NAMES:
            nested = child_dir / filename
            if nested.is_file():
                return nested

        nested_pt_files = sorted(
            [candidate for candidate in child_dir.iterdir() if candidate.is_file() and candidate.suffix == ".pt"],
            key=lambda candidate: candidate.stat().st_mtime,
            reverse=True,
        )
        if nested_pt_files:
            return nested_pt_files[0]

    return None


def resolve_dreamerv4_checkpoint_artifact(path: str | os.PathLike[str]) -> str:
    """Resolve a DreamerV4 checkpoint file from a file or checkpoint directory."""
    candidate = Path(path).expanduser()
    if candidate.is_file():
        return str(candidate.resolve())

    if candidate.is_dir():
        resolved = _find_checkpoint_file_in_directory(candidate)
        if resolved is not None:
            return str(resolved.resolve())

        raise FileNotFoundError(
            "No DreamerV4 checkpoint artifact was found under "
            f"{candidate}. Expected one of {DREAMERV4_CHECKPOINT_CANDIDATE_NAMES!r} "
            "or another .pt file."
        )

    raise FileNotFoundError(f"DreamerV4 checkpoint path does not exist: {candidate}")


def publish_dreamerv4_checkpoint(
    checkpoint_path: str | os.PathLike[str],
    destination: str | os.PathLike[str],
) -> str:
    """Copy a trained checkpoint into a drop-in runtime location.

    Parameters
    ----------
    checkpoint_path:
        Path to a checkpoint file or checkpoint directory produced by the trainer.
    destination:
        Either a target directory (the file will be written as
        ``dreamerv4_agent.pt``) or an explicit ``.pt`` file path.
    """
    source_file = Path(resolve_dreamerv4_checkpoint_artifact(checkpoint_path))
    destination_path = Path(destination).expanduser()
    if destination_path.suffix == ".pt":
        target_file = destination_path
    else:
        target_file = destination_path / DEFAULT_DREAMERV4_CHECKPOINT_NAME

    target_file.parent.mkdir(parents=True, exist_ok=True)
    if source_file.resolve() != target_file.resolve():
        shutil.copy2(source_file, target_file)
    _write_latest_marker(target_file)
    return str(target_file.resolve())


def _save_checkpoint(
    path: str,
    rssm: RSSM,
    actor: Actor,
    critic: Critic,
    target_critic: Critic,
    step: int,
) -> None:
    """Save all model weights and config."""
    ckpt = {
        "world_model": rssm.state_dict(),
        "actor": actor.state_dict(),
        "critic": critic.state_dict(),
        "target_critic": target_critic.state_dict(),
        "config": {
            "obs_dim": rssm.obs_dim,
            "action_dim": rssm.action_dim,
            "hidden_size": rssm.hidden_size,
            "stoch_categories": rssm.stoch_categories,
            "stoch_classes": rssm.stoch_classes,
            "mlp_units": rssm.mlp_units,
        },
        "step": step,
    }
    os.makedirs(os.path.dirname(path), exist_ok=True)
    torch.save(ckpt, path)
    _write_latest_marker(Path(path))


def _build_models_from_config(
    config: Dict[str, Any],
    device: torch.device,
    *,
    compile_models: bool = False,
) -> Tuple[RSSM, Actor, Critic, Critic]:
    """Instantiate fresh models from a config dict.

    When *compile_models* is True the Actor and Critic networks are wrapped
    with ``torch.compile``.  The RSSM is **not** compiled because its
    ``observe()`` method contains a Python for-loop (GRU unrolling) that
    ``aot_eager`` cannot fuse — on MPS the compilation wrapper dispatch
    overhead actually makes the sequential loop *slower*.  The Actor and
    Critic are pure feedforward and benefit from compilation.
    """
    rssm = RSSM(
        obs_dim=config["obs_dim"],
        action_dim=config["action_dim"],
        hidden_size=config["hidden_size"],
        stoch_categories=config["stoch_categories"],
        stoch_classes=config["stoch_classes"],
        mlp_units=config["mlp_units"],
    ).to(device)

    state_feat_dim = (
        config["hidden_size"] + config["stoch_categories"] * config["stoch_classes"]
    )

    actor = Actor(
        state_feat_dim=state_feat_dim,
        action_dim=config["action_dim"],
        mlp_units=config["mlp_units"],
    ).to(device)

    critic = Critic(
        state_feat_dim=state_feat_dim,
        mlp_units=config["mlp_units"],
    ).to(device)

    target_critic = Critic(
        state_feat_dim=state_feat_dim,
        mlp_units=config["mlp_units"],
    ).to(device)
    # Initialise target critic to match critic
    target_critic.load_state_dict(critic.state_dict())

    if compile_models:
        # Only compile pure-feedforward networks.  The RSSM's sequential
        # GRU loop prevents meaningful kernel fusion on MPS/aot_eager and
        # the wrapper dispatch overhead hurts throughput.
        actor = _maybe_compile(actor, device)
        critic = _maybe_compile(critic, device)
        target_critic = _maybe_compile(target_critic, device)

    return rssm, actor, critic, target_critic


def load_dreamerv4_pytorch_agent(
    checkpoint_path: str,
    *,
    seed: int = 0,
    step_hours: float = 6.0,
) -> DreamerV4PolicyAgent:
    """Load a trained DreamerV4 agent from a ``.pt`` checkpoint.

    Parameters
    ----------
    checkpoint_path : path to the ``.pt`` file
    seed : random seed (sets torch manual seed)
    step_hours : simulation step size (stored for reference, not used in policy)

    Returns
    -------
    DreamerV4PolicyAgent ready for inference
    """
    torch.manual_seed(seed)
    device = _auto_detect_device()
    resolved_checkpoint = resolve_dreamerv4_checkpoint_artifact(checkpoint_path)

    ckpt = torch.load(resolved_checkpoint, map_location=device, weights_only=False)
    config = ckpt["config"]

    rssm, actor, _, _ = _build_models_from_config(config, device)

    rssm.load_state_dict(ckpt["world_model"])
    actor.load_state_dict(ckpt["actor"])

    rssm.eval()
    actor.eval()

    return DreamerV4PolicyAgent(rssm, actor, device=device)


