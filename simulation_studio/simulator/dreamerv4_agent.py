def train_dreamerv4_native(args: argparse.Namespace) -> Dict[str, Any]:
    """Train a DreamerV4 agent on the blood supply simulation.

    ``args`` is expected to carry the fields documented in the module-level
    docstring (steps, seed, logdir, etc.).  Missing attributes fall back to
    sensible defaults.

    Metal GPU Optimisations
    -----------------------
    When the selected device is MPS (Apple Metal) the training loop applies
    the same class of acceleration techniques that the DreamerV3 JAX runner
    uses through ``jax-metal``:

    * **torch.compile (aot_eager)** — fuses Python dispatch overhead,
      analogous to JAX's XLA compilation cache.
    * **Async CPU ↔ GPU transfers** — ``non_blocking=True`` on tensor
      moves so the CPU can prepare the next batch while the GPU is busy.
    * **Reduced synchronisation** — ``optimizer.zero_grad(set_to_none=True)``
      avoids a GPU memset; ``.item()`` calls are batched to logging
      boundaries so intermediate gradient steps run without CPU stalls.
    * **MPS memory management** — ``PYTORCH_MPS_HIGH_WATERMARK_RATIO=0``
      lets the allocator grow/shrink dynamically (like JAX's
      ``XLA_PYTHON_CLIENT_PREALLOCATE=false``).
    * **MPS command-buffer flush** — ``torch.mps.synchronize()`` is called
      only at timing and checkpoint boundaries to avoid unnecessary stalls.
    Returns
    -------
    dict
        Runtime metadata including checkpoint and metrics paths. CLI callers
        can ignore the return value; notebook workflows use it directly.
    """
    # ---- lazy imports (avoid circular deps) ----
    from ppo_env import BloodSupplyEnv
    from ppo_shared import DREAMER_ACTION_DIM as ACTION_DIM
    from ppo_shared import OBS_DIM as OD
    from scenarios import SCENARIOS, TRAINING_SCENARIO_KEYS
    from train_mappo import load_training_context, prepare_mappo_scenario

    # ---- parse args with defaults ----
    steps: int = getattr(args, "steps", 50_000)
    seed: int = getattr(args, "seed", 0)
    logdir: str = getattr(args, "logdir", "dreamerv4_runs/default")
    step_hours: float = getattr(args, "step_hours", 6.0)
    scenario_str: str = getattr(args, "scenario", "train")
    batch_size: int = getattr(args, "batch_size", 16)
    requested_envs: int = int(getattr(args, "envs", 0))
    seq_len: int = getattr(args, "seq_len", 32)
    imagine_horizon: int = getattr(args, "imagine_horizon", 15)
    lr_world: float = getattr(args, "lr_world", 3e-4)
    lr_actor: float = getattr(args, "lr_actor", 1e-4)
    lr_critic: float = getattr(args, "lr_critic", 1e-4)
    save_every: int = getattr(args, "save_every", 5_000)
    log_every: int = getattr(args, "log_every", 100)
    prefill_steps: int = getattr(args, "prefill_steps", 1_000)
    train_ratio: float = max(0.0, float(getattr(args, "train_ratio", 1.0)))
    gamma: float = getattr(args, "gamma", 0.997)
    lambda_: float = getattr(args, "lambda_", 0.95)
    model_preset: str = str(getattr(args, "model_preset", "default"))
    hidden_size: int | None = getattr(args, "hidden_size", None)
    stoch_categories: int | None = getattr(args, "stoch_categories", None)
    stoch_classes: int | None = getattr(args, "stoch_classes", None)
    mlp_units: int | None = getattr(args, "mlp_units", None)
    device_str: str | None = getattr(args, "device", "auto")
    use_data_parallel: bool = bool(getattr(args, "use_data_parallel", True))
    max_cuda_devices: int = max(0, int(getattr(args, "max_cuda_devices", 0)))
    online_city_graph: bool = bool(getattr(args, "online_city_graph", False))

    # ---- reproducibility ----
    torch.manual_seed(seed)
    np.random.seed(seed)

    device = _resolve_device(device_str)
    cuda_device_ids = _resolve_cuda_device_ids(
        device,
        max_devices=max_cuda_devices,
    )
    data_parallel = _data_parallel_enabled(
        device,
        requested=use_data_parallel,
        batch_size=batch_size,
        device_ids=cuda_device_ids,
    )
    _configure_runtime_env(online_city_graph=online_city_graph)
    num_envs = _resolve_native_env_count(
        requested_envs,
        device=device,
        cuda_device_ids=cuda_device_ids,
    )

    # ---- Metal GPU detection (mirrors DreamerV3's choose_jax_runtime) ----
    _use_mps = device.type == "mps"
    _use_cuda = device.type == "cuda"
    _use_gpu = _use_mps or _use_cuda

    if _use_mps:
        print(
            "[DreamerV4] Apple Metal GPU detected — enabling MPS optimisations "
            "(torch.compile/aot_eager, async transfers, dynamic memory)",
            flush=True,
        )

    # ---- scenario handling ----
    if scenario_str == "train":
        scenario_keys = list(TRAINING_SCENARIO_KEYS)
    else:
        scenario_keys = [s.strip() for s in scenario_str.split(",")]

    scenario_templates = [prepare_mappo_scenario(SCENARIOS[k]) for k in scenario_keys]

    # ---- environment ----
    G, NORTH, SOUTH, EAST, WEST = load_training_context()

    envs = [
        BloodSupplyEnv(
            params=scenario_templates[0],
            G=G,
            north=NORTH,
            south=SOUTH,
            east=EAST,
            west=WEST,
            episode_hours=168.0,
            step_hours=step_hours,
            seed=seed + idx * 1000,
            scenario_templates=scenario_templates,
            action_mode="continuous",
        )
        for idx in range(num_envs)
    ]

    # ---- models (with optional torch.compile for GPU acceleration) ----
    config = _resolve_native_model_config(
        obs_dim=OD,
        action_dim=ACTION_DIM,
        preset=model_preset,
        hidden_size=hidden_size,
        stoch_categories=stoch_categories,
        stoch_classes=stoch_classes,
        mlp_units=mlp_units,
    )

    rssm, actor, critic, target_critic = _build_models_from_config(
        config,
        device,
        compile_models=_use_gpu and not data_parallel,
    )

    # ---- optimizers ----
    wm_optimizer = torch.optim.Adam(rssm.parameters(), lr=lr_world, eps=1e-5)
    actor_optimizer = torch.optim.Adam(actor.parameters(), lr=lr_actor, eps=1e-5)
    critic_optimizer = torch.optim.Adam(critic.parameters(), lr=lr_critic, eps=1e-5)
    world_model_parallel: nn.Module | None = None
    actor_critic_parallel: nn.Module | None = None
    if data_parallel:
        world_model_parallel = nn.DataParallel(
            _WorldModelLossModule(rssm),
            device_ids=cuda_device_ids,
            output_device=cuda_device_ids[0],
        )
        actor_critic_parallel = nn.DataParallel(
            _ActorCriticRolloutModule(rssm, actor, critic, target_critic),
            device_ids=cuda_device_ids,
            output_device=cuda_device_ids[0],
        )

    return_normalizer = ReturnNormalizer()
    replay = MultiEnvReplayBuffer(num_envs=num_envs, capacity=500_000)

    # ---- directories ----
    ckpt_dir = os.path.join(logdir, "ckpt")
    os.makedirs(ckpt_dir, exist_ok=True)
    metrics_path = os.path.join(logdir, "metrics.jsonl")

    # ---- metrics logging helper ----
    metric_buffer: List[Dict[str, Any]] = []

    def flush_metrics() -> None:
        if not metric_buffer:
            return
        with open(metrics_path, "a") as f:
            for m in metric_buffer:
                f.write(json.dumps(m) + "\n")
        metric_buffer.clear()

    def _reset_env(env_idx: int) -> np.ndarray:
        obs_raw = envs[env_idx].reset()
        if isinstance(obs_raw, tuple):
            obs_val, _ = obs_raw
        else:
            obs_val = obs_raw
        return np.asarray(obs_val, dtype=np.float32)

    # ---- MPS synchronisation helper ----
    def _mps_sync() -> None:
        """Flush the MPS command buffer so wall-clock timings are accurate.

        On non-MPS devices this is a no-op.  Equivalent to calling
        ``jax.block_until_ready`` in the DreamerV3 runner.
        """
        if _use_mps and hasattr(torch.mps, "synchronize"):
            torch.mps.synchronize()

    # ---- prefill ----
    print(
        f"[DreamerV4] Prefilling replay buffer with {prefill_steps} random steps ...",
        flush=True,
    )
    obs_vals = np.stack([_reset_env(env_idx) for env_idx in range(num_envs)], axis=0)
    is_first_flags = np.ones(num_envs, dtype=np.bool_)
    prefill_done = 0

    while prefill_done < prefill_steps:
        active_envs = min(num_envs, prefill_steps - prefill_done)
        actions = np.random.uniform(
            CONTINUOUS_ACTION_LOW,
            CONTINUOUS_ACTION_HIGH,
            size=(active_envs, ACTION_DIM),
        ).astype(np.float32)

        for env_idx in range(active_envs):
            action = actions[env_idx]
            step_result = envs[env_idx].step(action)
            if len(step_result) == 5:
                next_obs, reward, terminated, truncated, info = step_result
                done = terminated or truncated
            else:
                next_obs, reward, done, info = step_result

            replay.add(
                env_idx,
                obs_vals[env_idx],
                action,
                reward,
                bool(is_first_flags[env_idx]),
                done,
            )
            obs_vals[env_idx] = np.asarray(next_obs, dtype=np.float32)
            is_first_flags[env_idx] = False

            if done:
                obs_vals[env_idx] = _reset_env(env_idx)
                is_first_flags[env_idx] = True

        prefill_done += active_envs

    print(f"[DreamerV4] Replay buffer filled: {replay.size} transitions", flush=True)

    # ---- main training loop ----
    obs_vals = np.stack([_reset_env(env_idx) for env_idx in range(num_envs)], axis=0)
    is_first_flags = np.ones(num_envs, dtype=np.bool_)
    episode_rewards = np.zeros(num_envs, dtype=np.float32)
    episode_count = 0
    env_steps = 0
    grad_steps = 0
    _mps_sync()  # Flush any pending MPS work before starting the timer
    t_start = time.time()
    train_budget = 0.0
    policy_state = rssm.initial_state(num_envs, device)
    prev_action_t = torch.zeros(
        num_envs, ACTION_DIM, dtype=torch.float32, device=device
    )

    # Pre-allocate a reusable tensor for the first-step mask on the GPU so
    # we avoid a CPU→GPU transfer every collection step.  This mirrors the
    # JAX-style "donate buffer" pattern used by the DreamerV3 runner.
    _first_mask_buf = torch.zeros(num_envs, 1, dtype=torch.float32, device=device)

    # Accumulated metrics for logging
    wm_metrics_acc: Dict[str, list] = {}
    ac_metrics_acc: Dict[str, list] = {}

    print(f"[DreamerV4] Training for {steps} environment steps ...", flush=True)
    print(f"[DreamerV4]   device         = {device}")
    if _use_mps:
        print("[DreamerV4]   metal_gpu      = ENABLED (MPS + torch.compile/aot_eager)")
    elif _use_cuda:
        if data_parallel:
            print("[DreamerV4]   cuda_gpu       = ENABLED (multi-GPU data parallel)")
        else:
            print("[DreamerV4]   cuda_gpu       = ENABLED (torch.compile/inductor)")
    else:
        print("[DreamerV4]   accelerator    = none (CPU)")
    print(f"[DreamerV4]   logdir         = {logdir}")
    print(f"[DreamerV4]   scenarios      = {scenario_keys}")
    print(f"[DreamerV4]   envs           = {num_envs}")
    print(f"[DreamerV4]   model_preset   = {model_preset}")
    print(
        "[DreamerV4]   model_dims     = "
        f"h={config['hidden_size']} z={config['stoch_categories']}x{config['stoch_classes']} "
        f"mlp={config['mlp_units']}"
    )
    if data_parallel:
        print(
            f"[DreamerV4]   data_parallel  = ENABLED across CUDA devices {cuda_device_ids}",
            flush=True,
        )
    elif _use_cuda and len(cuda_device_ids) > 1 and use_data_parallel:
        print(
            "[DreamerV4]   data_parallel  = disabled because batch_size is smaller "
            "than the number of visible CUDA devices or a single CUDA device was selected.",
            flush=True,
        )
    print(f"[DreamerV4]   batch_size     = {batch_size}")
    print(f"[DreamerV4]   seq_len        = {seq_len}")
    print(f"[DreamerV4]   imagine_horizon= {imagine_horizon}")
    print(f"[DreamerV4]   train_ratio    = {train_ratio}", flush=True)
    print(
        "[DreamerV4]   simulator      = "
        f"{'online city graph' if online_city_graph else 'offline fast path'}",
        flush=True,
    )

    # Adaptive log schedule: log early so the user sees output quickly,
    # then settle into the regular ``log_every`` cadence.
    _early_log_steps = {1, 2, 5, 10, 25, 50}

    while env_steps < steps:
        prev_env_steps = env_steps
        active_envs = min(num_envs, steps - env_steps)

        # --- collect one environment step ---
        rssm.eval()
        actor.eval()

        with torch.no_grad():
            if active_envs < 1:
                break

            # Build first-step mask on GPU — write into pre-allocated buffer
            # instead of creating a new CPU tensor and transferring it each
            # iteration (a significant MPS latency win).
            _first_mask_buf[:active_envs, 0] = torch.as_tensor(
                is_first_flags[:active_envs], dtype=torch.float32, device=device
            )
            first_mask = _first_mask_buf[:active_envs]

            policy_state["h"][:active_envs] *= 1.0 - first_mask
            policy_state["z"][:active_envs] *= 1.0 - first_mask
            prev_action_t[:active_envs] *= 1.0 - first_mask

            # Async CPU→GPU transfer for observation tensor.
            obs_t = torch.from_numpy(obs_vals[:active_envs]).to(
                device, non_blocking=True
            )

            active_state = {
                "h": policy_state["h"][:active_envs],
                "z": policy_state["z"][:active_envs],
            }
            h = rssm.sequence_step(active_state, prev_action_t[:active_envs])
            embed = rssm.encode(obs_t)
            _, z = rssm.posterior(h, embed)
            policy_state["h"][:active_envs] = h
            policy_state["z"][:active_envs] = z
            feat = rssm.state_features({"h": h, "z": z})
            action_t, _, _ = actor(feat, sample=True)
            prev_action_t[:active_envs] = action_t.detach()
            actions = (
                action_t.cpu()
                .numpy()
                .clip(CONTINUOUS_ACTION_LOW, CONTINUOUS_ACTION_HIGH)
            )

        for env_idx in range(active_envs):
            step_result = envs[env_idx].step(actions[env_idx])
            if len(step_result) == 5:
                next_obs, reward, terminated, truncated, info = step_result
                done = terminated or truncated
            else:
                next_obs, reward, done, info = step_result

            replay.add(
                env_idx,
                obs_vals[env_idx],
                actions[env_idx],
                reward,
                bool(is_first_flags[env_idx]),
                done,
            )
            episode_rewards[env_idx] += float(reward)
            env_steps += 1
            obs_vals[env_idx] = np.asarray(next_obs, dtype=np.float32)
            is_first_flags[env_idx] = False

            if done:
                episode_count += 1
                metric_buffer.append(
                    {
                        "step": env_steps,
                        "episode": episode_count,
                        "episode_reward": float(episode_rewards[env_idx]),
                        "time": time.time() - t_start,
                    }
                )
                episode_rewards[env_idx] = 0.0
                obs_vals[env_idx] = _reset_env(env_idx)
                is_first_flags[env_idx] = True

        # --- gradient steps ---
        if (
            replay.size < batch_size * seq_len
            or train_ratio <= 0.0
            or not replay.can_sample(seq_len)
        ):
            continue
        train_budget += train_ratio * active_envs
        n_train_steps = int(train_budget)
        train_budget -= n_train_steps
        if n_train_steps < 1:
            continue

        rssm.train()
        actor.train()
        critic.train()

        for _ in range(n_train_steps):
            batch = replay.sample(batch_size, seq_len)

            # Train world model — also returns the final posterior state
            # so we can seed imagination without a redundant observe() call.
            wm_info, init_state = train_world_model(
                rssm,
                wm_optimizer,
                batch,
                device,
                free_nats=1.0,
                kl_balance=0.8,
                parallel_module=world_model_parallel,
            )
            for k, v in wm_info.items():
                wm_metrics_acc.setdefault(k, []).append(v)

            # Train actor-critic via imagination
            ac_info = train_actor_critic(
                rssm,
                actor,
                critic,
                target_critic,
                actor_optimizer,
                critic_optimizer,
                init_state,
                return_normalizer,
                horizon=imagine_horizon,
                gamma=gamma,
                lambda_=lambda_,
                entropy_coeff=3e-4,
                slow_critic_decay=0.98,
                parallel_module=actor_critic_parallel,
            )
            for k, v in ac_info.items():
                ac_metrics_acc.setdefault(k, []).append(v)

            grad_steps += 1

        # --- logging ---
        crossed_early_log = any(
            prev_env_steps < s <= env_steps for s in _early_log_steps
        )
        crossed_regular_log = log_every > 0 and (
            prev_env_steps // log_every != env_steps // log_every
        )
        _should_log = crossed_early_log or crossed_regular_log
        if _should_log:
            # Synchronise MPS before reading wall-clock so the timing
            # reflects actual GPU work, not just CPU-side dispatch.
            _mps_sync()
            elapsed = time.time() - t_start
            fps = env_steps / max(elapsed, 1e-6)

            log_entry: Dict[str, Any] = {
                "step": env_steps,
                "grad_steps": grad_steps,
                "episodes": episode_count,
                "fps": round(fps, 1),
                "buffer_size": replay.size,
            }

            # Average accumulated world-model metrics
            for k, vals in wm_metrics_acc.items():
                log_entry[k] = round(float(np.mean(vals)), 5)
            wm_metrics_acc.clear()

            # Average accumulated actor-critic metrics
            for k, vals in ac_metrics_acc.items():
                log_entry[k] = round(float(np.mean(vals)), 5)
            ac_metrics_acc.clear()

            metric_buffer.append(log_entry)
            flush_metrics()

            # Console summary
            wm_total = log_entry.get("wm/total", 0.0)
            ac_actor = log_entry.get("ac/actor_loss", 0.0)
            ac_critic = log_entry.get("ac/critic_loss", 0.0)
            print(
                f"[DreamerV4] step {env_steps:>7d} | grad {grad_steps:>7d} | "
                f"ep {episode_count:>4d} | fps {fps:5.1f} | "
                f"wm {wm_total:.4f} | act {ac_actor:.4f} | crit {ac_critic:.4f}",
                flush=True,
            )

        # --- checkpointing ---
        crossed_save_boundary = save_every > 0 and (
            prev_env_steps // save_every != env_steps // save_every
        )
        if crossed_save_boundary:
            # Ensure all MPS kernels have completed before writing to disk.
            _mps_sync()
            ckpt_path = os.path.join(ckpt_dir, DEFAULT_DREAMERV4_CHECKPOINT_NAME)
            _save_checkpoint(ckpt_path, rssm, actor, critic, target_critic, env_steps)
            print(
                f"[DreamerV4] Checkpoint saved -> {ckpt_path}  (step {env_steps})",
                flush=True,
            )
            # Release any MPS cached allocations back to the system after a
            # checkpoint so long-running sessions stay within memory budget.
            if _use_mps and hasattr(torch.mps, "empty_cache"):
                torch.mps.empty_cache()

    # ---- final save ----
    _mps_sync()
    flush_metrics()
    ckpt_path = os.path.join(ckpt_dir, DEFAULT_DREAMERV4_CHECKPOINT_NAME)
    _save_checkpoint(ckpt_path, rssm, actor, critic, target_critic, env_steps)
    print(
        f"[DreamerV4] Training complete.  Final checkpoint -> {ckpt_path}", flush=True
    )
    print(f"[DreamerV4]   total env steps  = {env_steps}")
    print(f"[DreamerV4]   total grad steps = {grad_steps}")
    print(f"[DreamerV4]   total episodes   = {episode_count}")
    elapsed_final = time.time() - t_start
    print(f"[DreamerV4]   wall time        = {elapsed_final:.1f}s", flush=True)
    if env_steps > 0:
        print(
            f"[DreamerV4]   avg throughput   = {env_steps / max(elapsed_final, 1e-6):.1f} env-steps/s",
            flush=True,
        )
    if _use_mps and hasattr(torch.mps, "empty_cache"):
        torch.mps.empty_cache()

    for env in envs:
        env.close()

    return {
        "device": str(device),
        "checkpoint_path": str(Path(ckpt_path).resolve()),
        "metrics_path": str(Path(metrics_path).resolve()),
        "logdir": str(Path(logdir).resolve()),
        "env_steps": int(env_steps),
        "grad_steps": int(grad_steps),
        "episodes": int(episode_count),
        "train_ratio": float(train_ratio),
        "envs": int(num_envs),
        "cuda_device_ids": list(cuda_device_ids),
        "data_parallel": bool(data_parallel),
        "model_config": dict(config),
    }


