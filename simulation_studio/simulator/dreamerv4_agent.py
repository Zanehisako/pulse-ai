class Actor(nn.Module):
    """TanhNormal policy network."""

    def __init__(self, state_feat_dim: int, action_dim: int, mlp_units: int = 256):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(state_feat_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
        )
        self.mean_head = nn.Linear(mlp_units, action_dim)
        self.log_std_head = nn.Linear(mlp_units, action_dim)
        self.action_dim = action_dim
        self._log_std_min = -5.0
        self._log_std_max = 2.0

    def forward(
        self,
        feat: torch.Tensor,
        *,
        sample: bool = True,
    ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Compute action, log-probability, and entropy.

        Returns
        -------
        action   : (*, action_dim)  in [-1, 1]
        log_prob : (*, )
        entropy  : (*, )
        """
        h = self.net(feat)
        mean = self.mean_head(h)
        log_std = self.log_std_head(h).clamp(self._log_std_min, self._log_std_max)
        std = log_std.exp()

        dist = Normal(mean, std)
        if sample:
            x = dist.rsample()
        else:
            x = mean

        # Tanh squash
        action = torch.tanh(x)

        # Log-prob with tanh correction
        log_prob = dist.log_prob(x) - torch.log(1.0 - action.pow(2) + 1e-6)
        log_prob = log_prob.sum(dim=-1)

        # Entropy (approximate via Normal entropy; tanh correction is small)
        entropy = dist.entropy().sum(dim=-1)

        return action, log_prob, entropy

    def act_eval(self, feat: torch.Tensor) -> torch.Tensor:
        """Deterministic action for evaluation (tanh of the mean)."""
        h = self.net(feat)
        mean = self.mean_head(h)
        return torch.tanh(mean)


class Critic(nn.Module):
    """State-value critic predicting symlog(value)."""

    def __init__(self, state_feat_dim: int, mlp_units: int = 256):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(state_feat_dim, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, mlp_units),
            nn.LayerNorm(mlp_units),
            nn.SiLU(),
            nn.Linear(mlp_units, 1),
        )

    def forward(self, feat: torch.Tensor) -> torch.Tensor:
        """Return symlog-encoded value prediction (*, 1)."""
        return self.net(feat)


