def symlog(x: torch.Tensor) -> torch.Tensor:
    """Symmetric logarithmic compression."""
    return torch.sign(x) * torch.log1p(torch.abs(x))


def symexp(x: torch.Tensor) -> torch.Tensor:
    """Inverse of symlog."""
    return torch.sign(x) * (torch.exp(torch.abs(x)) - 1.0)


def _straight_through_one_hot(logits: torch.Tensor, n_classes: int) -> torch.Tensor:
    """Sample one-hot from logits with straight-through gradients.

    Parameters
    ----------
    logits : (*, n_categories, n_classes)
    n_classes : int

    Returns
    -------
    one_hot : same shape as *logits*, hard one-hot forward, soft backward
    """
    probs = F.softmax(logits, dim=-1)
    indices = torch.argmax(
        probs + torch.rand_like(probs) * 1e-6,  # break ties
        dim=-1,
    )
    hard = F.one_hot(indices, n_classes).float()
    # Straight-through: forward uses hard, backward uses probs
    return hard + probs - probs.detach()


