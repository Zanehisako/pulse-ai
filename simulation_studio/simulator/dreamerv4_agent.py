class ReplayBuffer:
    """Contiguous replay storage with O(1) append and vectorized sampling."""

    def __init__(self, capacity: int = 500_000):
        self.capacity = capacity
        self._obs: np.ndarray | None = None
        self._action: np.ndarray | None = None
        self._reward: np.ndarray | None = None
        self._is_first: np.ndarray | None = None
        self._done: np.ndarray | None = None
        self._size = 0
        self._next_idx = 0

    @property
    def size(self) -> int:
        return self._size

    def _ensure_storage(self, obs: np.ndarray, action: np.ndarray) -> None:
        if self._obs is not None:
            return
        self._obs = np.empty((self.capacity, obs.size), dtype=np.float32)
        self._action = np.empty((self.capacity, action.size), dtype=np.float32)
        self._reward = np.empty((self.capacity,), dtype=np.float32)
        self._is_first = np.empty((self.capacity,), dtype=np.bool_)
        self._done = np.empty((self.capacity,), dtype=np.bool_)

    def _logical_to_physical(self, logical_idx: np.ndarray) -> np.ndarray:
        start = self._next_idx - self._size
        return (start + logical_idx) % self.capacity

    def add(
        self,
        obs: np.ndarray,
        action: np.ndarray,
        reward: float,
        is_first: bool,
        done: bool,
    ) -> None:
        """Add a single transition."""
        obs_arr = np.asarray(obs, dtype=np.float32).ravel()
        action_arr = np.asarray(action, dtype=np.float32).ravel()
        self._ensure_storage(obs_arr, action_arr)

        idx = self._next_idx
        assert self._obs is not None
        assert self._action is not None
        assert self._reward is not None
        assert self._is_first is not None
        assert self._done is not None

        self._obs[idx] = obs_arr
        self._action[idx] = action_arr
        self._reward[idx] = np.float32(reward)
        self._is_first[idx] = np.bool_(is_first)
        self._done[idx] = np.bool_(done)

        self._next_idx = (idx + 1) % self.capacity
        self._size = min(self._size + 1, self.capacity)

    def sample(
        self,
        batch_size: int,
        seq_len: int,
    ) -> Dict[str, np.ndarray]:
        """Sample uniform random subsequences.

        Returns dict with arrays of shape (batch_size, seq_len, ...).
        """
        max_start = self._size - seq_len
        if max_start < 1:
            raise RuntimeError(
                f"Buffer has {self._size} transitions but needs at least {seq_len + 1}."
            )

        starts = np.random.randint(0, max_start, size=batch_size)
        logical_idx = starts[:, None] + np.arange(seq_len)[None, :]
        physical_idx = self._logical_to_physical(logical_idx)

        assert self._obs is not None
        assert self._action is not None
        assert self._reward is not None
        assert self._is_first is not None
        assert self._done is not None

        return {
            "obs": self._obs[physical_idx],  # (B, T, obs_dim)
            "action": self._action[physical_idx],  # (B, T, act_dim)
            "reward": self._reward[physical_idx],  # (B, T)
            "is_first": self._is_first[physical_idx],  # (B, T)
            "done": self._done[physical_idx],  # (B, T)
        }


class MultiEnvReplayBuffer:
    """Independent per-env replay buffers with mixed-batch sampling."""

    def __init__(self, num_envs: int, capacity: int = 500_000):
        self.num_envs = max(1, int(num_envs))
        per_env_capacity = max(1, (int(capacity) + self.num_envs - 1) // self.num_envs)
        self._buffers = [ReplayBuffer(per_env_capacity) for _ in range(self.num_envs)]

    @property
    def size(self) -> int:
        return sum(buffer.size for buffer in self._buffers)

    def can_sample(self, seq_len: int) -> bool:
        return any(buffer.size > seq_len for buffer in self._buffers)

    def add(
        self,
        env_idx: int,
        obs: np.ndarray,
        action: np.ndarray,
        reward: float,
        is_first: bool,
        done: bool,
    ) -> None:
        self._buffers[int(env_idx)].add(obs, action, reward, is_first, done)

    def sample(
        self,
        batch_size: int,
        seq_len: int,
    ) -> Dict[str, np.ndarray]:
        eligible = [buffer for buffer in self._buffers if buffer.size > seq_len]
        if not eligible:
            raise RuntimeError(
                f"No replay buffer has enough transitions for seq_len={seq_len}."
            )

        selected = np.random.randint(0, len(eligible), size=batch_size)
        unique, counts = np.unique(selected, return_counts=True)
        parts = [
            eligible[int(idx)].sample(int(count), seq_len)
            for idx, count in zip(unique, counts)
        ]

        if len(parts) == 1:
            return parts[0]

        merged = {
            key: np.concatenate([part[key] for part in parts], axis=0)
            for key in parts[0]
        }
        order = np.random.permutation(batch_size)
        return {key: value[order] for key, value in merged.items()}


# ---------------------------------------------------------------------------
# Return Normalization (exponential moving percentiles)
# ---------------------------------------------------------------------------


class ReturnNormalizer:
    """Normalise returns using exponential moving 5th / 95th percentiles."""

    def __init__(
        self,
        decay: float = 0.99,
        percentile_low: float = 5.0,
        percentile_high: float = 95.0,
    ):
        self.decay = decay
        self.percentile_low = percentile_low
        self.percentile_high = percentile_high
        self._low = 0.0
        self._high = 1.0
        self._initialised = False

    def update(self, returns: torch.Tensor) -> None:
        flat = returns.detach().cpu().numpy().ravel()
        if flat.size == 0:
            return
        lo = float(np.percentile(flat, self.percentile_low))
        hi = float(np.percentile(flat, self.percentile_high))
        if not self._initialised:
            self._low = lo
            self._high = hi
            self._initialised = True
        else:
            self._low = self.decay * self._low + (1.0 - self.decay) * lo
            self._high = self.decay * self._high + (1.0 - self.decay) * hi

    def normalize(self, returns: torch.Tensor) -> torch.Tensor:
        span = max(self._high - self._low, 1e-8)
        return (returns - self._low) / span


# ---------------------------------------------------------------------------
# KL divergence helpers
# ---------------------------------------------------------------------------


def _categorical_kl(
    post_logits: torch.Tensor,
    prior_logits: torch.Tensor,
    free_nats: float = 1.0,
    balance: float = 0.8,
) -> Tuple[torch.Tensor, Dict[str, float]]:
    """Compute KL-balanced categorical KL with free bits.

    Parameters
    ----------
    post_logits, prior_logits : (B, T, n_cat, n_cls)
    free_nats : minimum KL per category
    balance   : fraction for dynamics loss (1 - balance for representation)

    Returns
    -------
    loss : scalar
    info : dict of logged scalars
    """
    post_probs = F.softmax(post_logits, dim=-1)
    _prior_probs = F.softmax(prior_logits, dim=-1)  # noqa: F841 — used only via log_softmax

    # KL per category: sum_c p(c) log(p(c)/q(c))
    kl_per_cat = (
        post_probs
        * (F.log_softmax(post_logits, dim=-1) - F.log_softmax(prior_logits, dim=-1))
    ).sum(dim=-1)  # (B, T, n_cat)

    # Free bits: clamp per category
    kl_free = torch.clamp(kl_per_cat, min=free_nats / post_logits.shape[-2])

    # Sum over categories → (B, T)
    kl_value = kl_free.sum(dim=-1)

    # KL balancing
    # dynamics loss: update prior towards posterior (stop-grad posterior)
    dyn_kl = (
        (
            F.softmax(post_logits.detach(), dim=-1)
            * (
                F.log_softmax(post_logits.detach(), dim=-1)
                - F.log_softmax(prior_logits, dim=-1)
            )
        )
        .sum(dim=-1)
        .sum(dim=-1)
    )  # (B, T)
    dyn_kl = torch.clamp(dyn_kl, min=0.0)

    # representation loss: update posterior towards prior (stop-grad prior)
    rep_kl = (
        (
            F.softmax(post_logits, dim=-1)
            * (
                F.log_softmax(post_logits, dim=-1)
                - F.log_softmax(prior_logits.detach(), dim=-1)
            )
        )
        .sum(dim=-1)
        .sum(dim=-1)
    )  # (B, T)
    rep_kl = torch.clamp(rep_kl, min=0.0)

    loss = balance * dyn_kl.mean() + (1.0 - balance) * rep_kl.mean()

    info = {
        "kl_value": float(kl_value.mean().item()),
        "kl_dyn": float(dyn_kl.mean().item()),
        "kl_rep": float(rep_kl.mean().item()),
    }
    return loss, info


def _batch_to_device_tensors(
    batch: Dict[str, np.ndarray],
    device: torch.device,
    *,
    non_blocking: bool = False,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    obs = torch.from_numpy(batch["obs"]).to(device, non_blocking=non_blocking)
    actions = torch.from_numpy(batch["action"]).to(device, non_blocking=non_blocking)
    rewards = torch.from_numpy(batch["reward"]).to(device, non_blocking=non_blocking)
    is_first = torch.from_numpy(batch["is_first"].astype("float32")).to(
        device, non_blocking=non_blocking
    )
    dones = torch.from_numpy(batch["done"].astype("float32")).to(
        device, non_blocking=non_blocking
    )
    return obs, actions, rewards, is_first, dones


class _WorldModelLossModule(nn.Module):
    """Compute world-model losses in a form that can be data-parallelised."""

    def __init__(self, rssm: RSSM):
        super().__init__()
        self.rssm = rssm

    def forward(
        self,
        obs: torch.Tensor,
        actions: torch.Tensor,
        rewards: torch.Tensor,
        is_first: torch.Tensor,
        dones: torch.Tensor,
        free_nats: float,
        kl_balance: float,
        kl_scale: float,
    ) -> Dict[str, torch.Tensor]:
        B, T, _ = obs.shape
        prev_actions = torch.cat(
            [torch.zeros(B, 1, actions.shape[-1], device=obs.device), actions[:, :-1]],
            dim=1,
        )

        out = self.rssm.observe(obs, prev_actions, is_first)
        feat = out["feat_seq"]

        obs_pred = self.rssm.decode_obs(feat)
        obs_target = symlog(obs)
        obs_loss = F.mse_loss(obs_pred, obs_target)

        rew_pred = self.rssm.decode_reward(feat).squeeze(-1)
        rew_target = symlog(rewards)
        rew_loss = F.mse_loss(rew_pred, rew_target)

        cont_pred = self.rssm.decode_continue(feat).squeeze(-1)
        cont_target = 1.0 - dones.float()
        cont_loss = F.binary_cross_entropy_with_logits(cont_pred, cont_target)

        kl_loss, kl_info = _categorical_kl(
            out["post_logits"],
            out["prior_logits"],
            free_nats=free_nats,
            balance=kl_balance,
        )
        total_loss = obs_loss + rew_loss + cont_loss + kl_scale * kl_loss

        return {
            "total_loss": total_loss.unsqueeze(0),
            "obs_loss": obs_loss.detach().unsqueeze(0),
            "rew_loss": rew_loss.detach().unsqueeze(0),
            "cont_loss": cont_loss.detach().unsqueeze(0),
            "kl_value": torch.tensor(
                [kl_info["kl_value"]], device=obs.device, dtype=torch.float32
            ),
            "kl_dyn": torch.tensor(
                [kl_info["kl_dyn"]], device=obs.device, dtype=torch.float32
            ),
            "kl_rep": torch.tensor(
                [kl_info["kl_rep"]], device=obs.device, dtype=torch.float32
            ),
            "chunk_weight": torch.tensor([float(B)], device=obs.device),
            "final_h": out["final_state"]["h"].detach(),
            "final_z": out["final_state"]["z"].detach(),
        }


class _ActorCriticRolloutModule(nn.Module):
    """Compute actor/critic rollout tensors for optional data parallelism."""

    def __init__(
        self,
        rssm: RSSM,
        actor: Actor,
        critic: Critic,
        target_critic: Critic,
    ):
        super().__init__()
        self.rssm = rssm
        self.actor = actor
        self.critic = critic
        self.target_critic = target_critic

    def forward(
        self,
        initial_h: torch.Tensor,
        initial_z: torch.Tensor,
        horizon: int,
        gamma: float,
        lambda_: float,
    ) -> Dict[str, torch.Tensor]:
        initial_state = {"h": initial_h, "z": initial_z}
        traj = imagine_trajectory(self.rssm, self.actor, initial_state, horizon)

        feats = traj["feats"]
        feats_detached = feats.detach()
        rewards = symexp(traj["reward_preds"].detach())
        continues = traj["continue_preds"]

        with torch.no_grad():
            target_values_sym = self.target_critic(feats_detached).squeeze(-1)
            target_values = symexp(target_values_sym)
            lambda_returns = compute_lambda_returns(
                rewards, target_values, continues.detach(), gamma, lambda_
            )

        values_sym = self.critic(feats_detached).squeeze(-1)

        return {
            "log_probs": traj["log_probs"],
            "entropies": traj["entropies"],
            "lambda_returns": lambda_returns.detach(),
            "values_sym": values_sym,
            "values_for_adv": target_values.detach(),
            "chunk_weight": torch.tensor(
                [float(initial_h.shape[0])], device=initial_h.device
            ),
        }


# ---------------------------------------------------------------------------
# World-model training step
# ---------------------------------------------------------------------------


def train_world_model(
    rssm: RSSM,
    optimizer: torch.optim.Optimizer,
    batch: Dict[str, np.ndarray],
    device: torch.device,
    free_nats: float = 1.0,
    kl_balance: float = 0.8,
    kl_scale: float = 1.0,
    parallel_module: nn.Module | None = None,
    _non_blocking: bool = False,
) -> Tuple[Dict[str, float], Dict[str, torch.Tensor]]:
    """One gradient step on the world model.

    Returns
    -------
    (metrics_dict, final_state)
        *final_state* can be reused as the imagination starting point so the
        caller does not need a redundant ``rssm.observe`` call.
    """
    # Use non_blocking=True for async CPU→GPU transfer when the source
    # tensors live in pinned (page-locked) memory.  On MPS this allows the
    # CPU to continue filling the next batch while the current transfer
    # proceeds over the unified-memory fabric.
    nb = _non_blocking
    obs, actions, rewards, is_first, dones = _batch_to_device_tensors(
        batch,
        device,
        non_blocking=nb,
    )

    if parallel_module is None:
        B, T, _ = obs.shape

        # Shift actions so action[t] is the action *before* obs[t]
        prev_actions = torch.cat(
            [torch.zeros(B, 1, actions.shape[-1], device=device), actions[:, :-1]],
            dim=1,
        )

        out = rssm.observe(obs, prev_actions, is_first)
        feat = out["feat_seq"]  # (B, T, 512)

        # --- Reconstruction loss (symlog MSE) ---
        obs_pred = rssm.decode_obs(feat)  # (B, T, obs_dim)
        obs_target = symlog(obs)
        obs_loss = F.mse_loss(obs_pred, obs_target)

        # --- Reward loss (symlog MSE) ---
        rew_pred = rssm.decode_reward(feat).squeeze(-1)  # (B, T)
        rew_target = symlog(rewards)
        rew_loss = F.mse_loss(rew_pred, rew_target)

        # --- Continue loss (binary cross-entropy) ---
        cont_pred = rssm.decode_continue(feat).squeeze(-1)  # (B, T)
        cont_target = 1.0 - dones.float()
        cont_loss = F.binary_cross_entropy_with_logits(cont_pred, cont_target)

        # --- KL loss ---
        kl_loss, kl_info = _categorical_kl(
            out["post_logits"],
            out["prior_logits"],
            free_nats=free_nats,
            balance=kl_balance,
        )

        total_loss = obs_loss + rew_loss + cont_loss + kl_scale * kl_loss

        optimizer.zero_grad(set_to_none=True)
        total_loss.backward()
        nn.utils.clip_grad_norm_(rssm.parameters(), 100.0)
        optimizer.step()

        final_state = {k: v.detach() for k, v in out["final_state"].items()}

        metrics = {
            "wm/total": float(total_loss.item()),
            "wm/obs": float(obs_loss.item()),
            "wm/rew": float(rew_loss.item()),
            "wm/cont": float(cont_loss.item()),
            "wm/kl": float(kl_info["kl_value"]),
            "wm/kl_dyn": float(kl_info["kl_dyn"]),
            "wm/kl_rep": float(kl_info["kl_rep"]),
        }
        return metrics, final_state

    outputs = parallel_module(
        obs,
        actions,
        rewards,
        is_first,
        dones,
        free_nats,
        kl_balance,
        kl_scale,
    )
    weights = outputs["chunk_weight"].reshape(-1)
    total_loss = (outputs["total_loss"].reshape(-1) * weights).sum() / weights.sum()

    optimizer.zero_grad(set_to_none=True)
    total_loss.backward()
    nn.utils.clip_grad_norm_(rssm.parameters(), 100.0)
    optimizer.step()

    final_state = {
        "h": outputs["final_h"].detach(),
        "z": outputs["final_z"].detach(),
    }
    metrics = {
        "wm/total": float(total_loss.item()),
        "wm/obs": float(
            (outputs["obs_loss"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
        "wm/rew": float(
            (outputs["rew_loss"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
        "wm/cont": float(
            (outputs["cont_loss"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
        "wm/kl": float(
            (outputs["kl_value"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
        "wm/kl_dyn": float(
            (outputs["kl_dyn"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
        "wm/kl_rep": float(
            (outputs["kl_rep"].reshape(-1) * weights).sum().item() / weights.sum().item()
        ),
    }
    return metrics, final_state


# ---------------------------------------------------------------------------
# Imagination rollout & actor-critic training
# ---------------------------------------------------------------------------


def imagine_trajectory(
    rssm: RSSM,
    actor: Actor,
    initial_state: Dict[str, torch.Tensor],
    horizon: int,
) -> Dict[str, torch.Tensor]:
    """Roll out the actor in the learned world model.

    Parameters
    ----------
    initial_state : dict with "h" (B, H) and "z" (B, stoch_dim)
    horizon : number of imagined steps

    Returns
    -------
    Dict with feats, actions, log_probs, entropies, reward_preds,
    continue_preds — all (B, horizon, ...).

    """
    feats = []
    actions = []
    log_probs = []
    entropies = []
    reward_preds = []
    continue_preds = []

    state = {k: v.detach() for k, v in initial_state.items()}

    for _ in range(horizon):
        # The actor loss below is REINFORCE-style and only uses log-probs.
        # Keep imagined dynamics detached so we do not backpropagate through
        # the world model or through earlier imagined actions.
        feat = rssm.state_features(state).detach()
        action, lp, ent = actor(feat, sample=True)

        feats.append(feat)
        actions.append(action.detach())
        log_probs.append(lp)
        entropies.append(ent)

        with torch.no_grad():
            # Predict reward and continue from current state
            reward_preds.append(rssm.decode_reward(feat).squeeze(-1))
            continue_preds.append(torch.sigmoid(rssm.decode_continue(feat).squeeze(-1)))

            # Step world model forward (no observation — use prior)
            h = rssm.sequence_step(state, action.detach())
            _, z = rssm.prior(h)
            state = {"h": h.detach(), "z": z.detach()}

    return {
        "feats": torch.stack(feats, dim=1),  # (B, H, feat_dim)
        "actions": torch.stack(actions, dim=1),  # (B, H, act_dim)
        "log_probs": torch.stack(log_probs, dim=1),  # (B, H)
        "entropies": torch.stack(entropies, dim=1),  # (B, H)
        "reward_preds": torch.stack(reward_preds, dim=1),  # (B, H)
        "continue_preds": torch.stack(continue_preds, dim=1),  # (B, H)
    }


def compute_lambda_returns(
    rewards: torch.Tensor,
    values: torch.Tensor,
    continues: torch.Tensor,
    gamma: float,
    lambda_: float,
) -> torch.Tensor:
    """Compute GAE-style lambda-returns.

    Parameters
    ----------
    rewards    : (B, H)  — predicted rewards (symexp decoded)
    values     : (B, H)  — value predictions (symexp decoded)
    continues  : (B, H)  — continue probabilities
    gamma, lambda_ : discount and trace-decay

    Returns
    -------
    returns : (B, H)
    """
    B, H = rewards.shape
    returns = torch.zeros_like(rewards)
    last = values[:, -1]

    for t in reversed(range(H)):
        if t == H - 1:
            next_val = last
        else:
            next_val = (1.0 - lambda_) * values[:, t + 1] + lambda_ * returns[:, t + 1]
        returns[:, t] = rewards[:, t] + gamma * continues[:, t] * next_val

    return returns


def train_actor_critic(
    rssm: RSSM,
    actor: Actor,
    critic: Critic,
    target_critic: Critic,
    actor_optimizer: torch.optim.Optimizer,
    critic_optimizer: torch.optim.Optimizer,
    initial_state: Dict[str, torch.Tensor],
    return_normalizer: ReturnNormalizer,
    horizon: int = 15,
    gamma: float = 0.997,
    lambda_: float = 0.95,
    entropy_coeff: float = 3e-4,
    slow_critic_decay: float = 0.98,
    parallel_module: nn.Module | None = None,
) -> Dict[str, float]:
    """One gradient step for actor and critic via imagination."""
    if parallel_module is None:
        traj = imagine_trajectory(rssm, actor, initial_state, horizon)

        feats = traj["feats"]
        feats_detached = feats.detach()
        rewards_sym = traj["reward_preds"]
        continues = traj["continue_preds"]
        log_probs = traj["log_probs"]
        entropies = traj["entropies"]

        rewards = symexp(rewards_sym.detach())

        with torch.no_grad():
            target_values_sym = target_critic(feats_detached).squeeze(-1)
            target_values = symexp(target_values_sym)
            lambda_returns = compute_lambda_returns(
                rewards, target_values, continues.detach(), gamma, lambda_
            )
            return_normalizer.update(lambda_returns)

        values_sym = critic(feats_detached).squeeze(-1)
        values_for_adv = symexp(target_critic(feats_detached).squeeze(-1))
    else:
        outputs = parallel_module(
            initial_state["h"],
            initial_state["z"],
            horizon,
            gamma,
            lambda_,
        )
        lambda_returns = outputs["lambda_returns"]
        values_sym = outputs["values_sym"]
        log_probs = outputs["log_probs"]
        entropies = outputs["entropies"]
        values_for_adv = outputs["values_for_adv"]
        return_normalizer.update(lambda_returns)

    critic_target = symlog(lambda_returns)
    critic_loss = F.mse_loss(values_sym, critic_target.detach())

    critic_optimizer.zero_grad(set_to_none=True)
    critic_loss.backward()
    nn.utils.clip_grad_norm_(critic.parameters(), 100.0)
    critic_optimizer.step()

    # --- Actor loss ---
    with torch.no_grad():
        advantages = lambda_returns - values_for_adv
        normed_advantages = return_normalizer.normalize(
            lambda_returns
        ) - return_normalizer.normalize(values_for_adv)

    # Reinforce + straight-through objective
    actor_loss = -(normed_advantages.detach() * log_probs).mean()
    entropy_loss = -entropy_coeff * entropies.mean()
    total_actor_loss = actor_loss + entropy_loss

    actor_optimizer.zero_grad(set_to_none=True)
    total_actor_loss.backward()
    nn.utils.clip_grad_norm_(actor.parameters(), 100.0)
    actor_optimizer.step()

    # --- Update slow critic (EMA) ---
    with torch.no_grad():
        for p, tp in zip(critic.parameters(), target_critic.parameters()):
            tp.data.mul_(slow_critic_decay).add_(p.data, alpha=1.0 - slow_critic_decay)

    return {
        "ac/actor_loss": float(actor_loss.item()),
        "ac/critic_loss": float(critic_loss.item()),
        "ac/entropy": float(entropies.mean().item()),
        "ac/return_mean": float(lambda_returns.mean().item()),
        "ac/advantage_mean": float(advantages.mean().item()),
    }


