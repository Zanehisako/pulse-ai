"""
dreamerv4_agent.py — Native PyTorch DreamerV4 agent for the blood supply
chain simulation.

Implements the DreamerV4 world-model-based reinforcement learning agent
(Hafner et al., "Mastering Diverse Domains through World Models" with V4
improvements) entirely in PyTorch.  The agent learns a latent world model
(RSSM), then trains an actor–critic pair purely inside imagined
trajectories generated by that model.

Exported symbols
----------------
- ``DreamerV4PolicyAgent``              — inference wrapper (drop-in for the
  JAX-based DreamerV3 agent used elsewhere in the simulator)
- ``load_dreamerv4_pytorch_agent``      — reconstruct agent from checkpoint
- ``train_dreamerv4_native``            — main training entry-point

The policy interface matches the existing ``trained_official_dreamerv3_
controller`` contract so the agent can be swapped in without changes to
``engine.py``.
"""

