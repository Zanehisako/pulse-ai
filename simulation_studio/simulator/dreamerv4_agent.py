def _is_apple_silicon() -> bool:
    """True when running on an Apple Silicon Mac."""
    return platform.system() == "Darwin" and platform.machine().lower() in {
        "arm64",
        "aarch64",
    }


def _mps_is_available() -> bool:
    """Check MPS availability without triggering heavy initialisation."""
    try:
        return (
            hasattr(torch.backends, "mps")
            and torch.backends.mps.is_available()
            and torch.backends.mps.is_built()
        )
    except Exception:
        return False


def _configure_mps_runtime() -> None:
    """Apply MPS-specific environment and runtime knobs.

    This is the PyTorch equivalent of ``configure_process_env`` in the
    DreamerV3 JAX runner — it tunes memory allocation, enables operation
    fallback, and warms the MPS shader cache so the first forward pass
    is not disproportionately slow.
    """
    # Dynamic memory management — avoids the MPS allocator reserving the
    # entire GPU VRAM up-front which can cause OOM on shared-memory Macs.
    os.environ.setdefault("PYTORCH_MPS_HIGH_WATERMARK_RATIO", MPS_HIGH_WATERMARK_RATIO)
    os.environ.setdefault("PYTORCH_MPS_LOW_WATERMARK_RATIO", MPS_LOW_WATERMARK_RATIO)
    # Allow ops without a Metal kernel to fall back to CPU transparently.
    os.environ.setdefault("PYTORCH_ENABLE_MPS_FALLBACK", "1")


def _configure_cuda_runtime() -> None:
    """Apply safe CUDA performance defaults for notebook and CLI training."""
    if not torch.cuda.is_available():
        return
    if hasattr(torch, "set_float32_matmul_precision"):
        torch.set_float32_matmul_precision("high")
    if hasattr(torch.backends, "cuda") and hasattr(torch.backends.cuda, "matmul"):
        torch.backends.cuda.matmul.allow_tf32 = True
    if hasattr(torch.backends, "cudnn"):
        torch.backends.cudnn.allow_tf32 = True
        torch.backends.cudnn.benchmark = True


def _auto_detect_device() -> torch.device:
    """Pick the best available accelerator: CUDA → MPS (Apple Silicon) → CPU.

    When MPS is selected the function also calls ``_configure_mps_runtime``
    so that all Metal-specific knobs are set before the first kernel launch.
    """
    if torch.cuda.is_available():
        _configure_cuda_runtime()
        return torch.device("cuda")
    if _mps_is_available():
        _configure_mps_runtime()
        return torch.device("mps")
    return torch.device("cpu")


def _resolve_device(name: str | None) -> torch.device:
    """Resolve a user-supplied device string (or *None* for auto-detect)."""
    if name is None or name == "auto":
        return _auto_detect_device()
    device = torch.device(name)
    if device.type == "mps":
        _configure_mps_runtime()
    elif device.type == "cuda":
        _configure_cuda_runtime()
    return device


def _resolve_cuda_device_ids(
    device: torch.device,
    *,
    max_devices: int = 0,
) -> list[int]:
    """Return the visible CUDA device ids that should participate in training."""
    if device.type != "cuda" or not torch.cuda.is_available():
        return []

    if device.index is not None:
        return [int(device.index)]

    count = int(torch.cuda.device_count())
    if max_devices > 0:
        count = min(count, int(max_devices))
    return list(range(count))


def _data_parallel_enabled(
    device: torch.device,
    *,
    requested: bool,
    batch_size: int,
    device_ids: list[int],
) -> bool:
    if not requested or device.type != "cuda":
        return False
    if len(device_ids) < 2:
        return False
    return int(batch_size) >= len(device_ids)


def _configure_runtime_env(*, online_city_graph: bool = False) -> None:
    """Align native training defaults with the official Dreamer runtime."""
    if not online_city_graph:
        os.environ.setdefault("PIOS_SIM_OFFLINE", "1")


def _resolve_native_env_count(
    requested_envs: int,
    *,
    device: torch.device | None = None,
    cuda_device_ids: list[int] | None = None,
) -> int:
    """Choose a practical default number of collection envs."""
    if requested_envs > 0:
        return requested_envs
    workers = max(1, int(os.cpu_count() or 1))
    if device is not None and device.type == "cuda":
        gpu_count = max(1, len(cuda_device_ids or []) or int(torch.cuda.device_count()))
        return min(8, max(2 * gpu_count, workers // 2))
    return min(4, max(1, workers // 2))


_M = TypeVar("_M", bound=nn.Module)


def _maybe_compile(
    module: _M,
    device: torch.device,
    *,
    disable: bool = False,
) -> _M:
    """Wrap *module* with ``torch.compile`` when the backend supports it.

    On MPS (Apple Metal) we use the ``aot_eager`` backend which fuses
    Python overhead and enables operator fusion without requiring a full
    Inductor/Triton stack.  On CUDA the default ``inductor`` backend is
    used.  Compilation is skipped on CPU or when *disable* is True.

    This is the PyTorch analogue of the JAX XLA compilation cache that
    the DreamerV3 Metal runner enables via ``XDG_CACHE_HOME``.
    """
    if disable:
        return module
    if not hasattr(torch, "compile"):
        return module  # PyTorch < 2.0
    try:
        if device.type == "mps":
            return torch.compile(module, backend="aot_eager")  # type: ignore[return-value]
        if device.type == "cuda":
            return torch.compile(module, mode="reduce-overhead")  # type: ignore[return-value]
    except Exception:
        # Graceful degradation — compilation is best-effort.
        pass
    return module


